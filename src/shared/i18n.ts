/** 取文案：lang 缺省按中文；支持 {param} 插值；未知键回落中文再回落键名。 */
export function t(lang: Language | undefined, key: StringKey, params?: Record<string, string | number>): string {
  const text = lang === 'en' ? en[key] : zh[key]
  if (text === undefined) return key
  if (!params) return text
  let result = text
  for (const [name, value] of Object.entries(params)) result = result.replaceAll(`{${name}}`, String(value))
  return result
}

export const GROWTH_LEVEL_KEYS: readonly StringKey[] = ['growth.sprout', 'growth.little', 'growth.round', 'growth.honey', 'growth.immortal']

export function growthLevelName(lang: Language | undefined, level: number): string {
  const index = Math.min(Math.max(level, 1), GROWTH_LEVEL_KEYS.length) - 1
  return t(lang, GROWTH_LEVEL_KEYS[index])
}

/** 称呼前缀：中文「名字，」，英文「Name, 」。 */
export function callNamePrefix(lang: Language | undefined, nickname: string): string {
  if (!nickname) return ''
  return lang === 'en' ? `${nickname}, ` : `${nickname}，`
}

export function formatDurationLocalized(lang: Language | undefined, seconds: number): string {
  const h = Math.floor(seconds / 3600)
  const m = Math.floor((seconds % 3600) / 60)
  return h ? t(lang, 'duration.h', { h, m }) : t(lang, 'duration.m', { m })
}

/** 按语言返回本地化日期格式化器。 */
export function dateFormatter(lang: Language | undefined): Intl.DateTimeFormat {
  return new Intl.DateTimeFormat(lang === 'en' ? 'en-US' : 'zh-CN', {
    year: 'numeric', month: 'long', day: 'numeric', weekday: 'long'
  })
}
